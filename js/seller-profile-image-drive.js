/* Bookora seller profile image: mandatory Google Drive upload + URL sync.
 * The seller must upload a profile image. The resulting Google Drive URL is
 * automatically written into the existing Portfolio / Author Profile URL field.
 * No manual profile-image URL entry is required or allowed.
 */
import { state } from './state.js';
import { Toast } from './components/Toast.js';

(() => {
  'use strict';

  const API_ROOT = String(window.BOOKORA_API_URL || 'https://bookora-backend-x08l.onrender.com').replace(/\/$/, '');
  const MAX_BYTES = 5 * 1024 * 1024;
  const ALLOWED = new Set(['image/jpeg', 'image/png', 'image/webp']);
  let selectedFile = null;
  let uploadedMeta = null;
  let uploadPromise = null;

  function authHeaders(extra = {}) {
    const out = { ...extra };
    if (state.token) out.Authorization = `Bearer ${state.token}`;
    return out;
  }

  async function json(response) {
    const data = await response.json().catch(() => ({}));
    if (!response.ok || data.success === false) throw new Error(data.error || `Request failed (HTTP ${response.status})`);
    return data;
  }

  function setStatus(text, kind = 'info') {
    const el = document.getElementById('seller-profile-image-status');
    if (!el) return;
    el.textContent = text;
    el.dataset.kind = kind;
  }

  function profileUrlField() {
    return document.getElementById('apply-portfolio');
  }

  function syncGeneratedUrl(url) {
    const input = profileUrlField();
    if (!input) return;
    input.value = String(url || '');
    input.readOnly = true;
    input.required = true;
    input.dataset.autoGenerated = 'true';
    input.dataset.userTouched = '1';
    input.placeholder = 'Generated automatically after image upload';
    input.dispatchEvent(new Event('input', { bubbles: true }));
    input.dispatchEvent(new Event('change', { bubbles: true }));
  }

  function renderPreview(meta, file) {
    const img = document.getElementById('seller-profile-image-preview');
    const placeholder = document.getElementById('seller-profile-image-placeholder');
    const remove = document.getElementById('seller-profile-image-remove');
    if (!img || !placeholder) return;
    const src = file ? URL.createObjectURL(file) : (meta?.url || '');
    if (src) {
      img.src = src;
      img.hidden = false;
      placeholder.hidden = true;
      if (remove) remove.hidden = false;
    } else {
      img.removeAttribute('src');
      img.hidden = true;
      placeholder.hidden = false;
      if (remove) remove.hidden = true;
    }
  }

  function validateFile(file) {
    if (!file) throw new Error('Profile image is required. Please upload an image.');
    if (!ALLOWED.has(file.type)) throw new Error('Profile image must be JPG, PNG, or WebP.');
    if (file.size > MAX_BYTES) throw new Error('Profile image must be 5 MB or smaller.');
  }

  async function uploadToDrive(file) {
    validateFile(file);
    if (uploadedMeta?.localKey === `${file.name}:${file.size}:${file.lastModified}` && uploadedMeta.url) return uploadedMeta;
    if (uploadPromise) return uploadPromise;

    uploadPromise = (async () => {
      setStatus('Uploading profile image to Google Drive…', 'loading');
      const startRes = await fetch(`${API_ROOT}/api/books/upload-session/start`, {
        method: 'POST',
        headers: authHeaders({ 'Content-Type': 'application/json' }),
        body: JSON.stringify({ name: `seller-profile-${Date.now()}-${file.name}`, mimeType: file.type, size: file.size, kind: 'profile-image' })
      });
      const started = await json(startRes);
      const token = started.upload_token;
      const chunkBytes = Math.max(256 * 1024, Math.min(Number(started.chunk_size) || 4 * 1024 * 1024, 4 * 1024 * 1024));
      let offset = Number(started.next_offset || 0);

      while (offset < file.size) {
        const end = Math.min(file.size, offset + chunkBytes);
        const bytes = await new Promise((resolve, reject) => {
          const reader = new FileReader();
          reader.onload = () => resolve(new Uint8Array(reader.result));
          reader.onerror = () => reject(new Error('Could not read an upload chunk.'));
          reader.readAsArrayBuffer(file.slice(offset, end));
        });
        let binary = '';
        for (let i = 0; i < bytes.length; i += 0x8000) binary += String.fromCharCode(...bytes.subarray(i, Math.min(i + 0x8000, bytes.length)));
        const chunkRes = await fetch(`${API_ROOT}/api/books/upload-session/chunk`, {
          method: 'POST',
          headers: authHeaders({ 'Content-Type': 'application/json' }),
          body: JSON.stringify({ upload_token: token, offset, data: btoa(binary) })
        });
        const result = await json(chunkRes);
        offset = Number(result.next_offset || end);
        setStatus(`Uploading profile image… ${Math.round((offset / file.size) * 100)}%`, 'loading');
      }

      const statusRes = await fetch(`${API_ROOT}/api/books/upload-session/status`, {
        method: 'POST',
        headers: authHeaders({ 'Content-Type': 'application/json' }),
        body: JSON.stringify({ upload_token: token })
      });
      const status = await json(statusRes);
      if (!status.file?.file_id || !status.file?.url) throw new Error('Google Drive upload completed without a usable file URL.');
      uploadedMeta = {
        fileId: status.file.file_id,
        url: status.file.url,
        name: file.name,
        mimeType: file.type,
        size: file.size,
        storage: 'google_drive',
        localKey: `${file.name}:${file.size}:${file.lastModified}`
      };
      syncGeneratedUrl(uploadedMeta.url);
      setStatus('Profile image uploaded. The profile URL was filled automatically.', 'success');
      return uploadedMeta;
    })().finally(() => { uploadPromise = null; });

    return uploadPromise;
  }

  function injectUI() {
    const form = document.getElementById('seller-apply-form');
    if (!form || document.getElementById('seller-profile-image-field')) return false;
    const firstSection = form.querySelector('.seller-section');
    if (!firstSection) return false;
    const portfolio = document.getElementById('apply-portfolio');
    if (!portfolio) return false;

    const portfolioField = portfolio.closest('.seller-field');
    if (portfolioField) {
      const label = portfolioField.querySelector('label');
      if (label) label.innerHTML = 'Profile Image <span class="seller-profile-required">*</span>';
      portfolioField.dataset.profileImageUrlField = 'true';
      portfolio.placeholder = 'Upload an image below — URL will be generated automatically';
      portfolio.readOnly = true;
      portfolio.required = true;
      portfolio.autocomplete = 'off';
      portfolio.title = 'This URL is generated automatically from your Google Drive profile image.';
      portfolio.addEventListener('keydown', e => e.preventDefault());
      portfolio.addEventListener('paste', e => e.preventDefault());
      portfolio.addEventListener('drop', e => e.preventDefault());
    }

    const wrap = document.createElement('div');
    wrap.id = 'seller-profile-image-field';
    wrap.className = 'seller-profile-image-field';
    wrap.innerHTML = `
      <div class="seller-field">
        <label>Upload Profile Image <span class="seller-profile-required">*</span></label>
        <div id="seller-profile-image-drop" class="seller-profile-image-drop" tabindex="0" role="button" aria-label="Upload required profile image">
          <div class="seller-profile-image-preview-wrap">
            <img id="seller-profile-image-preview" alt="Profile preview" hidden>
            <div id="seller-profile-image-placeholder" class="seller-profile-image-placeholder">+</div>
          </div>
          <div class="seller-profile-image-copy">
            <strong>Drag & drop your profile image here</strong>
            <span>or click to browse • JPG, PNG, WebP • max 5 MB</span>
            <small id="seller-profile-image-status">Required. The image will be stored in Google Drive and its URL will be filled automatically above.</small>
          </div>
          <button id="seller-profile-image-remove" type="button" hidden>Remove</button>
          <input id="seller-profile-image-input" type="file" accept="image/jpeg,image/png,image/webp" required hidden>
        </div>
      </div>`;
    portfolioField?.insertAdjacentElement('afterend', wrap);

    const drop = document.getElementById('seller-profile-image-drop');
    const input = document.getElementById('seller-profile-image-input');
    const remove = document.getElementById('seller-profile-image-remove');
    const choose = file => {
      try {
        validateFile(file);
        selectedFile = file;
        uploadedMeta = null;
        syncGeneratedUrl('');
        renderPreview(null, file);
        setStatus('Image selected. Uploading to Google Drive will start when you submit.', 'info');
      } catch (error) {
        selectedFile = null;
        renderPreview(null, null);
        syncGeneratedUrl('');
        setStatus(error.message, 'error');
        Toast.show(error.message, 'warning');
      }
    };
    drop.addEventListener('click', event => { if (event.target !== remove) input.click(); });
    drop.addEventListener('keydown', event => { if (event.key === 'Enter' || event.key === ' ') { event.preventDefault(); input.click(); } });
    input.addEventListener('change', () => choose(input.files?.[0]));
    ['dragenter', 'dragover'].forEach(type => drop.addEventListener(type, event => { event.preventDefault(); drop.classList.add('is-dragging'); }));
    ['dragleave', 'drop'].forEach(type => drop.addEventListener(type, event => { event.preventDefault(); drop.classList.remove('is-dragging'); }));
    drop.addEventListener('drop', event => choose(event.dataTransfer?.files?.[0]));
    remove.addEventListener('click', event => {
      event.stopPropagation();
      selectedFile = null;
      uploadedMeta = null;
      input.value = '';
      syncGeneratedUrl('');
      renderPreview(null, null);
      setStatus('Profile image is required. Please upload an image.', 'error');
    });
    return true;
  }

  async function loadExisting() {
    if (!state.token || !document.getElementById('seller-apply-form')) return;
    try {
      const res = await fetch(`${API_ROOT}/api/seller/application`, { headers: authHeaders() });
      if (!res.ok) return;
      const data = await res.json();
      const app = data.application || {};
      const meta = app.profileImage || {};
      const url = meta.url || app.profileImageUrl || app.avatarUrl || '';
      const fileId = meta.fileId || app.profileImageFileId || app.profileImageDriveFileId || '';
      if (!url && !fileId) return;
      uploadedMeta = { fileId, url, name: meta.name || 'profile-image', mimeType: meta.mimeType || '', size: Number(meta.size || 0), storage: 'google_drive', localKey: '' };
      syncGeneratedUrl(url);
      renderPreview(uploadedMeta, null);
      setStatus('Profile image loaded from your saved seller record.', 'success');
    } catch (error) {
      console.warn('Seller profile image load skipped:', error);
    }
  }

  function patchSellerApplyFetch() {
    if (window.__BOOKORA_PROFILE_IMAGE_FETCH_PATCHED__) return;
    const originalFetch = window.fetch.bind(window);
    window.fetch = async function profileImageSellerApplyFetch(input, init = {}) {
      const url = typeof input === 'string' ? input : input?.url || '';
      if (!String(url).includes('/api/seller/apply')) return originalFetch(input, init);
      let payload;
      try { payload = typeof init.body === 'string' ? JSON.parse(init.body) : null; } catch (_) { payload = null; }
      if (!payload) return originalFetch(input, init);

      if (!selectedFile && !uploadedMeta?.url) {
        const message = 'Profile image is required. Please upload your profile image before submitting.';
        Toast.show(message, 'warning');
        throw new Error(message);
      }
      try {
        const meta = selectedFile ? await uploadToDrive(selectedFile) : uploadedMeta;
        if (!meta?.fileId || !meta?.url) throw new Error('Profile image upload did not return a valid Google Drive URL.');
        payload.profileImage = { fileId: meta.fileId, url: meta.url, name: meta.name, mimeType: meta.mimeType, size: meta.size, storage: 'google_drive' };
        payload.profileImageFileId = meta.fileId;
        payload.profileImageUrl = meta.url;
        payload.profileImageDriveFileId = meta.fileId;
        payload.profileImageStorage = 'google_drive';
        payload.portfolioUrl = meta.url;
        init = { ...init, body: JSON.stringify(payload), headers: authHeaders(init.headers || {}) };
      } catch (error) {
        Toast.show(error.message || 'Profile image upload failed. Application was not submitted.', 'error');
        throw error;
      }
      return originalFetch(input, init);
    };
    window.__BOOKORA_PROFILE_IMAGE_FETCH_PATCHED__ = true;
  }

  function addStyles() {
    if (document.getElementById('seller-profile-image-styles')) return;
    const style = document.createElement('style');
    style.id = 'seller-profile-image-styles';
    style.textContent = `
      .seller-profile-image-field{margin:0 0 1.25rem}
      .seller-profile-required{color:#dc2626;font-weight:800}
      .seller-profile-image-drop{display:flex;align-items:center;gap:1rem;padding:1rem;border:1.5px dashed #cbd5e1;border-radius:14px;background:#f8fafc;cursor:pointer;transition:.18s ease}
      .seller-profile-image-drop:hover,.seller-profile-image-drop.is-dragging{border-color:var(--accent);background:#faf7ff}
      .seller-profile-image-preview-wrap{width:72px;height:72px;flex:none;border-radius:50%;overflow:hidden;border:1px solid #e2e8f0;background:#fff;display:grid;place-items:center}
      .seller-profile-image-preview-wrap img{width:100%;height:100%;object-fit:cover}
      .seller-profile-image-placeholder{font-size:2rem;color:#94a3b8;font-weight:300}
      .seller-profile-image-copy{display:grid;gap:.2rem;min-width:0}.seller-profile-image-copy strong{font-size:.9rem;color:#0f172a}.seller-profile-image-copy span,.seller-profile-image-copy small{font-size:.75rem;color:#64748b;line-height:1.4}.seller-profile-image-copy small[data-kind="error"]{color:#dc2626}.seller-profile-image-copy small[data-kind="success"]{color:#15803d}
      #seller-profile-image-remove{margin-left:auto;border:1px solid #cbd5e1;background:#fff;border-radius:8px;padding:.45rem .65rem;cursor:pointer;color:#475569}
      #apply-portfolio[data-auto-generated="true"]{background:#f8fafc;cursor:not-allowed}
      @media(max-width:640px){.seller-profile-image-drop{align-items:flex-start;flex-wrap:wrap}.seller-profile-image-copy{flex:1;min-width:180px}#seller-profile-image-remove{margin-left:84px}}
    `;
    document.head.appendChild(style);
  }

  function validateBeforeSubmit() {
    const form = document.getElementById('seller-apply-form');
    if (!form || !location.hash.includes('/seller/apply')) return;
    const imageInput = document.getElementById('seller-profile-image-input');
    const urlInput = profileUrlField();
    if (imageInput) imageInput.required = true;
    if (urlInput) urlInput.required = true;
    if (form.dataset.profileImageValidationBound === '1') return;
    form.addEventListener('submit', event => {
      if (!selectedFile && !uploadedMeta?.url) {
        event.preventDefault();
        event.stopImmediatePropagation();
        setStatus('Profile image is required. Please upload an image before submitting.', 'error');
        Toast.show('Profile image is required. Please upload your profile image.', 'warning');
        document.getElementById('seller-profile-image-drop')?.focus();
        return false;
      }
    }, true);
    form.dataset.profileImageValidationBound = '1';
  }

  function boot() {
    if (!location.hash.includes('/seller/apply')) return;
    if (injectUI()) {
      addStyles();
      validateBeforeSubmit();
      patchSellerApplyFetch();
      loadExisting();
    } else if (document.getElementById('seller-apply-form')) {
      addStyles();
      validateBeforeSubmit();
      patchSellerApplyFetch();
      loadExisting();
    }
  }

  const observer = new MutationObserver(() => boot());
  const start = () => {
    if (!document.body) return;
    observer.observe(document.body, { childList: true, subtree: true });
    boot();
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start, { once: true });
  else start();
  window.addEventListener('hashchange', () => setTimeout(boot, 0));
})();
